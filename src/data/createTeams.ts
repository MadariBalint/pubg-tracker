export function createTeams(teamCount: number, playersPerTeam: number): Team[] {
  return Array.from({ length: teamCount }, (_, index) => ({
    id: index + 3,
    slot: index + 3,
    name: teamNames[index + 2] ?? `Team ${index + 3}`,
    flag: flagMap[index + 2] ?? "🏳️",
    alivePlayers: playersPerTeam,
  }));
}
